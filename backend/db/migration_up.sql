-- 1. USERS
-- Stores host accounts.
CREATE TABLE users (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    CONSTRAINT users_username_not_empty
        CHECK (LENGTH(TRIM(username)) > 0),
    CONSTRAINT users_email_not_empty
        CHECK (LENGTH(TRIM(email)) > 0)
);

-- 2. PLAYLISTS
-- Each playlist represents a party hosted by a user.
CREATE TABLE playlists (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    date_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    host_id INTEGER NOT NULL,
    -- Spotify is the only supported provider in V1.
    streaming_service VARCHAR(50) NOT NULL DEFAULT 'spotify',
    -- Optional external playlist ID from the streaming provider.
    streaming_playlist_id VARCHAR(255),
    -- Unique code used by guests to join the party.
    invite_code VARCHAR(100) NOT NULL UNIQUE,
    -- preparing: the host can add tracks directly.
    -- active: the host and guests can propose tracks for voting.
    -- finished: the party has ended.
    status VARCHAR(20) NOT NULL DEFAULT 'preparing',
    CONSTRAINT playlists_host_fk
        FOREIGN KEY (host_id)
        REFERENCES users(id)
        ON DELETE CASCADE,
    CONSTRAINT playlists_name_not_empty
        CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT playlists_streaming_service_not_empty
        CHECK (LENGTH(TRIM(streaming_service)) > 0),
    CONSTRAINT playlists_status_check
        CHECK (status IN ('preparing', 'active', 'finished'))
);
-- Speeds up playlist lookups by host.
CREATE INDEX idx_playlists_host_id ON playlists(host_id);
-- 3. PLAYLIST_GUESTS
-- Stores guests who join a party without creating an account.
CREATE TABLE playlist_guests (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    playlist_id INTEGER NOT NULL,
    guest_name VARCHAR(50) NOT NULL,
    -- Unique token generated by the backend to identify a guest.
    guest_token VARCHAR(255) NOT NULL UNIQUE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT playlist_guests_playlist_fk
        FOREIGN KEY (playlist_id)
        REFERENCES playlists(id)
        ON DELETE CASCADE,
    CONSTRAINT playlist_guests_name_not_empty
        CHECK (LENGTH(TRIM(guest_name)) > 0),
    -- Allows composite foreign keys to verify playlist membership.
    CONSTRAINT playlist_guests_id_playlist_unique
        UNIQUE (id, playlist_id)
);

-- Speeds up guest lookups by playlist.
CREATE INDEX idx_playlist_guests_playlist_id
ON playlist_guests(playlist_id);

-- 4. TRACKS
-- Stores tracks added by the host or proposed by guests.
CREATE TABLE tracks (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    playlist_id INTEGER NOT NULL,
    -- NULL when the track was added by the host.
    guest_id INTEGER,
    -- Track information retrieved from Spotify.
    external_track_id VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    artist VARCHAR(255) NOT NULL,
    image_url TEXT,
    duration_ms INTEGER NOT NULL,
    -- Identifies who added the track:
    -- host: the party organizer.
    -- guest: a guest who joined the party.
    added_by VARCHAR(10) NOT NULL,
    -- proposed: waiting to enter a voting round.
    -- voting: currently included in a voting round.
    -- selected: accepted into the final playlist.
    -- played: already played during the party.
    -- Before the party starts, host tracks are directly selected.
    -- During the party, host and guest proposals must be voted on.
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tracks_playlist_fk
        FOREIGN KEY (playlist_id)
        REFERENCES playlists(id)
        ON DELETE CASCADE,
    -- Ensures that the guest belongs to the same playlist.
    CONSTRAINT tracks_guest_fk
        FOREIGN KEY (guest_id, playlist_id)
        REFERENCES playlist_guests(id, playlist_id),
    -- Prevents duplicate Spotify tracks within the same playlist.
    CONSTRAINT tracks_unique_external_id
        UNIQUE (playlist_id, external_track_id),
    CONSTRAINT tracks_added_by_check
        CHECK (added_by IN ('host', 'guest')),
    CONSTRAINT tracks_status_check
        CHECK (status IN ('proposed', 'voting', 'selected', 'played')),
    -- Host tracks have no guest ID.
    -- Guest tracks must reference a guest.
    CONSTRAINT tracks_origin_check
        CHECK (
            (added_by = 'host' AND guest_id IS NULL)
            OR
            (added_by = 'guest' AND guest_id IS NOT NULL)
        ),
    -- A track duration must be greater than zero.
    CONSTRAINT tracks_duration_positive
        CHECK (duration_ms > 0)
);

-- Improves queries filtering tracks by playlist and status.
CREATE INDEX idx_tracks_playlist_status
ON tracks(playlist_id, status);

-- 5. VOTING_SESSIONS
-- Represents voting rounds within a party.
CREATE TABLE voting_sessions (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    playlist_id INTEGER NOT NULL,
    round_number INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT voting_sessions_playlist_fk
        FOREIGN KEY (playlist_id)
        REFERENCES playlists(id)
        ON DELETE CASCADE,
    -- Prevents duplicate round numbers in the same playlist.
    CONSTRAINT voting_sessions_unique_round
        UNIQUE (playlist_id, round_number),
    CONSTRAINT voting_sessions_status_check
        CHECK (status IN ('active', 'closed')),
    -- Round numbers must be positive.
    CONSTRAINT voting_sessions_round_positive
        CHECK (round_number > 0),
    -- Allows composite references to a voting session and its playlist.
    CONSTRAINT voting_sessions_id_playlist_unique
        UNIQUE (id, playlist_id)
);

-- 6. VOTING_POOL
-- Stores the tracks selected for each voting round.
-- The backend will enforce a maximum of 15 tracks per round.
CREATE TABLE voting_pool (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    voting_session_id INTEGER NOT NULL,
    track_id INTEGER NOT NULL,
    CONSTRAINT voting_pool_session_fk
        FOREIGN KEY (voting_session_id)
        REFERENCES voting_sessions(id)
        ON DELETE CASCADE,
    CONSTRAINT voting_pool_track_fk
        FOREIGN KEY (track_id)
        REFERENCES tracks(id)
        ON DELETE CASCADE,
    -- Prevents the same track from appearing twice in one round.
    CONSTRAINT voting_pool_unique_track
        UNIQUE (voting_session_id, track_id),
    -- Allows votes to reference a track in a specific voting round.
    CONSTRAINT voting_pool_id_session_unique
        UNIQUE (id, voting_session_id)
);

-- 7. VOTES
-- Stores votes from hosts and guests.
-- Each participant can vote only once per voting round.
CREATE TABLE votes (
    id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    voting_session_id INTEGER NOT NULL,
    voting_pool_id INTEGER NOT NULL,
    -- A vote can come from either a host or a guest.
    -- Only one of these fields can be populated.
    host_id INTEGER,
    guest_id INTEGER,
    voted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT votes_session_fk
        FOREIGN KEY (voting_session_id)
        REFERENCES voting_sessions(id)
        ON DELETE CASCADE,
    -- Ensures that the voted track belongs to the voting round.
    CONSTRAINT votes_pool_session_fk
        FOREIGN KEY (voting_pool_id, voting_session_id)
        REFERENCES voting_pool(id, voting_session_id)
        ON DELETE CASCADE,
    CONSTRAINT votes_host_fk
        FOREIGN KEY (host_id)
        REFERENCES users(id)
        ON DELETE CASCADE,
    CONSTRAINT votes_guest_fk
        FOREIGN KEY (guest_id)
        REFERENCES playlist_guests(id)
        ON DELETE CASCADE,
    -- A vote must belong to either a host or a guest, never both.
    CONSTRAINT votes_voter_check
        CHECK (
            (host_id IS NOT NULL AND guest_id IS NULL)
            OR
            (host_id IS NULL AND guest_id IS NOT NULL)
        ),
    -- Prevents the host from voting multiple times in one round.
    CONSTRAINT votes_unique_host_session
        UNIQUE (voting_session_id, host_id),
    -- Prevents a guest from voting multiple times in one round.
    CONSTRAINT votes_unique_guest_session
        UNIQUE (voting_session_id, guest_id)
);